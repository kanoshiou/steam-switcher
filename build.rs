// Build script, two jobs:
//
// 1. Embeds `assets/icon.ico` into the executable so Explorer, the taskbar
//    and the exe properties show the app icon (the tray icon is drawn at
//    runtime by `tray::render_rgba`, the same design the .ico is generated
//    from). Regenerate the .ico after changing the design:
//    `cargo run --example gen-icon`.
//
// 2. Generates `app_icons.rs`: an `include_bytes!` loader for exactly the
//    Lucide SVGs this app references. `gpui-kit-assets` offers the full
//    catalog (`AllAssets`, ~1830 icons) or the component defaults; both are
//    far more than the app uses, so every `IconName::*` under `src/` is
//    scanned out and only those files are embedded. `src/app.rs` layers this
//    bundle under the gpui-component default bundle.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=build.rs");
    embed_windows_icon();
    generate_icon_loader();
}

fn embed_windows_icon() {
    // CARGO_CFG_WINDOWS is set when compiling for a Windows target.
    if std::env::var_os("CARGO_CFG_WINDOWS").is_some() {
        let icon = "assets/icon.ico";
        if !Path::new(icon).is_file() {
            // Fresh checkout before the icon was ever generated.
            println!(
                "cargo:warning=assets/icon.ico not found; exe will use the default icon. \
                 Run `cargo run --example gen-icon` to generate it."
            );
            return;
        }
        winresource::WindowsResource::new()
            .set_icon(icon)
            .compile()
            .expect("failed to embed assets/icon.ico into the executable");
    }
}

/// Write `$OUT_DIR/app_icons.rs` with a `load(path)` matching only the icons
/// the app's source actually references.
fn generate_icon_loader() {
    let variants = used_icon_variants();
    let icons_dir = gpui_kit_assets_icons_dir();

    let mut match_arms = String::new();
    let mut listed = String::new();
    for variant in &variants {
        let stem = kebab_case(variant);
        let svg = icons_dir.join("icons").join(format!("{stem}.svg"));
        if !svg.is_file() {
            panic!(
                "IconName::{variant} (icons/{stem}.svg) not found in {}",
                icons_dir.display()
            );
        }
        let path = format!("icons/{stem}.svg");
        let bytes = svg.display();
        match_arms.push_str(&format!(
            "            \"{path}\" => Some(include_bytes!(r#\"{bytes}\"#)),\n"
        ));
        listed.push_str(&format!(r#"            "{path}","#));
        listed.push('\n');
    }

    let code = format!(
        "// @generated by build.rs — bytes for every `IconName` used under `src/`.\n\
         /// Bytes for an app-referenced icon asset path, if embedded.\n\
         pub fn load(path: &str) -> Option<&'static [u8]> {{\n\
         \x20   match path {{\n{match_arms}\
         \x20       _ => None,\n\
         \x20   }}\n\
         }}\n\
         /// Every embedded icon asset path.\n\
         pub fn list() -> Vec<&'static str> {{\n\
         \x20   vec![\n{listed}\
         \x20   ]\n\
         }}\n"
    );

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo OUT_DIR"));
    std::fs::write(out_dir.join("app_icons.rs"), code).expect("write generated app icon loader");
}

/// Every `IconName::X` referenced anywhere under `src/`.
fn used_icon_variants() -> BTreeSet<String> {
    let mut variants = BTreeSet::new();
    let mut stack = vec![PathBuf::from("src")];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("read src/ tree").flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            let text = std::fs::read_to_string(&path).expect("read source file");
            let mut rest = &text[..];
            while let Some(index) = rest.find("IconName::") {
                rest = &rest[index + "IconName::".len()..];
                let end = rest
                    .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .unwrap_or(rest.len());
                let variant = &rest[..end];
                if !variant.is_empty() {
                    variants.insert(variant.to_string());
                }
            }
        }
    }
    variants
}

/// `SlidersHorizontal` → `sliders-horizontal`, `Gamepad2` → `gamepad-2`:
/// a dash goes before every uppercase letter and before a digit run that
/// follows a letter.
fn kebab_case(variant: &str) -> String {
    let mut kebab = String::new();
    let mut chars = variant.chars().peekable();
    while let Some(c) = chars.next() {
        let dash = kebab.ends_with(|p: char| p.is_ascii_lowercase())
            && (c.is_ascii_uppercase()
                || (c.is_ascii_digit()
                    && !chars.peek().is_some_and(|n| n.is_ascii_digit())));
        if dash {
            kebab.push('-');
        }
        kebab.extend(c.to_lowercase());
    }
    kebab
}

/// Locate the checked-out `gpui-kit-assets` crate that supplies the SVGs,
/// via `cargo metadata` (the registry source path is not otherwise exposed
/// to build scripts).
fn gpui_kit_assets_icons_dir() -> PathBuf {
    let manifest = Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"))
        .join("Cargo.toml");
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let output = Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--manifest-path"])
        .arg(&manifest)
        .output()
        .expect("run cargo metadata");
    if !output.status.success() {
        panic!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let metadata: serde_json::Value =
        serde_json::from_slice(&output.stdout).expect("parse cargo metadata JSON");
    let packages = metadata["packages"].as_array().expect("packages array");
    for package in packages {
        if package["name"] == "gpui-kit-assets" {
            let manifest_path = PathBuf::from(package["manifest_path"].as_str().expect("path"));
            return manifest_path.parent().expect("crate dir").join("assets");
        }
    }
    panic!("gpui-kit-assets not found in cargo metadata output");
}
