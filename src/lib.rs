//! steam-switcher library root.
//!
//! Module map (see docs/plan.md for the phased roadmap):
//! - [`steam`]: Steam interaction core (discovery, loginusers.vdf, library, launching)
//! - [`app`]:   application bootstrap and the tray/event bridge
//! - [`app_window`]: the gpui settings window (sidebar + pages)
//! - [`tray`]:  tray icon and context menu
//! - [`singleton`], [`autostart`], [`winutil`], [`notify`], [`logging`]:
//!   OS-integration helpers

// i18n: translations live in `locales/*.yml`, English is the fallback.
rust_i18n::i18n!("locales", fallback = "en");

/// Bytes for every `IconName` referenced under `src/`, generated by build.rs
/// (the gpui-component defaults come from `gpui_kit::assets::Assets`).
#[cfg(feature = "gui")]
mod app_icons {
    include!(concat!(env!("OUT_DIR"), "/app_icons.rs"));
}

pub mod autostart;
pub mod config;
pub mod logging;
pub mod notify;
pub mod singleton;
pub mod steam;

/// Switch-flow glue (blocking switch execution, lenient account loading)
/// shared verbatim by the gui and tray-only builds.
#[cfg(windows)]
pub mod switch_flow;

/// gpui theme palette (gui builds only).
#[cfg(all(windows, feature = "gui"))]
pub mod theme;
pub mod tray;

/// Windows-specific helpers (message box, win32 message pump).
#[cfg(windows)]
pub mod winutil;

/// The gpui settings window (sidebar + pages; gui builds only).
#[cfg(all(windows, feature = "gui"))]
pub mod app_window;

/// Tray-only application loop (tray icon + win32 message pump, no window).
/// Mounted as `app` so `main` calls `app::run()` unchanged in both builds.
#[cfg(all(windows, not(feature = "gui")))]
#[path = "app_tray.rs"]
pub mod app;

/// GUI application bootstrap and event loop (gpui + tray bridging).
#[cfg(all(windows, feature = "gui"))]
pub mod app;

/// Non-Windows builds have no tray/GUI yet (Windows-first; see docs/plan.md).
#[cfg(not(windows))]
pub mod app {
    /// Stub entry point so the crate still checks on other platforms.
    pub fn run() -> anyhow::Result<()> {
        eprintln!("steam-switcher: tray GUI is Windows-only in this phase");
        Ok(())
    }}

